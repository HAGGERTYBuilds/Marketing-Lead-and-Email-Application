-- Kept here as the record, with the steps the routine follows.
--
-- The Social tab's Send button marks the month's approved posts 'queued'
-- and adds a social_jobs row of kind 'send_cloud'. The laptop task only
-- handles generate, extras and send, so it leaves these alone. A Claude
-- routine ("Social send to Metricool", hourly 7 AM to 7 PM Pacific) picks
-- them up. Generate and extras stay on the laptop: they read the J: archive.

alter table public.social_jobs drop constraint social_jobs_kind_check;
alter table public.social_jobs add constraint social_jobs_kind_check
  check (kind = any (array['generate','send','extras','send_cloud']));

-- Instant push (2026-11-02)
-- -------------------------
-- The Social tab now asks n8n to send right away: after any save that
-- leaves a post queued, it POSTs (signed in) to
-- https://haggertybuilds.app.n8n.cloud/webhook/haggerty-social-push, the
-- n8n workflow "Haggerty Social Push To Metricool" (malH1xo2wX6efGKW). It
-- claims every pending send_cloud job, creates the drafts through the
-- Metricool API (header X-Mc-Auth, credential "Metricool API"; needs the
-- Advanced plan) with exactly the rules in steps 2 to 5 below, saves
-- social_posts.metricool and finishes the job (result.by = 'n8n instant
-- push'). Posts approved while it runs are picked up before it stops.
-- The routine stays on at 8:17, 12:17 and 4:17 as the backup and usually
-- finds nothing to claim. Neither claims a job whose brand and month
-- another run started sending in the last 10 minutes, so the two can
-- never send the same post twice. No database change was needed.
--
-- Send waiting now (Social tab button, staff only): queues this brand's
-- approved posts dated before today (reviewed ones only, for a brand with
-- a reviewer), then calls the same webhook with release = true. In release
-- mode n8n also starts a job for any queued post that has none, and a post
-- whose time has passed goes to Metricool for tomorrow at its usual time,
-- with old_post, original and sent_for saved on that half in
-- social_posts.metricool. The card shows an Old post tag.

-- What the routine does on each run
-- ---------------------------------
-- 1. Claim the oldest pending job, so two runs can't both send it:
--      update social_jobs set status = 'running', started_at = now()
--       where id = (select id from social_jobs
--                    where kind = 'send_cloud' and status = 'pending'
--                      and not exists (select 1 from social_jobs r
--                           where r.kind = 'send_cloud' and r.status = 'running'
--                             and r.brand = social_jobs.brand and r.month = social_jobs.month
--                             and r.started_at > now() - interval '10 minutes')
--                    order by created_at limit 1)
--         and status = 'pending'
--      returning *;
--    Nothing returned means nothing to do.
--
-- 2. Read the job's posts: social_posts where brand and month match the job
--    and status = 'queued', with social_post_media ordered by position.
--    Media URL: https://ekatzukprjpisdiwubjq.supabase.co/storage/v1/object/
--    public/social-media/<storage_path, each segment URL-encoded>.
--
-- 3. For each post, Metricool createScheduledPost on the job's brand:
--    haggerty = blogId 5357410, rhino = blogId 6222867 (RHINO Restores,
--    since 2026-10-15). Any other brand: fail the job, send nothing.
--    Timezone America/Los_Angeles, draft true. These are drafts in
--    Metricool only: the routine never publishes; a person does that in
--    Metricool:
--    When social_posts.post_time is set (sql/social_post_time.sql), both
--    halves go at post_date + post_time instead of 10:00 / 11:00.
--    When social_posts.networks is set (sql/social_networks.sql), send only
--    to the networks in it: half a. goes to whichever of Instagram and
--    Facebook are listed (skip it when neither is), half b. only when
--    linkedin is listed. A half that is skipped counts as done.
--      a. Instagram + Facebook at post_date 10:00. Text = caption, a blank
--         line, hashtags. instagramData.type and facebookData.type are
--         REEL when the post has a video, else POST.
--      b. LinkedIn at post_date 11:00. Text = caption, a blank line,
--         hashtags_li (or hashtags when that is empty).
--         linkedinData {previewIncluded: true, type: "post"}.
--      c. Google Business Profile (since 2026-11-02, sql/social_google.sql),
--         When networks includes 'google', or networks is null (null =
--         all four networks since 2026-11-02, see sql/social_google.sql).
--         Provider network "gmb" at post_date 10:00 (or post_time).
--         Text = caption only, no hashtags, cut to 1,500 characters.
--         Media = the first photo only (none when the post is video only).
--         gmbData {type: "publication"}. Saved as metricool.gmb.
--    Skip a half already recorded in social_posts.metricool (ig_fb,
--    linkedin or gmb), so a retry never makes a duplicate draft.
--    A post dated before today stays queued and is named in the note.
--    A post with no media stays queued: Instagram needs a photo or video.
--
-- 4. After both halves: update social_posts set status = 'sent',
--    sent_at = now(), metricool = {"ig_fb": {id, uuid, plannerUrl},
--    "linkedin": {id, uuid, plannerUrl}}. After one half only: save that
--    half in metricool and leave the post queued.
--
-- 5. Finish the job: status 'done' when every queued post went, else
--    'failed'; finished_at = now(); note = one or two plain sentences
--    the Social tab shows, naming each post by date and topic, and any
--    other post already in Metricool at the same date and time.
